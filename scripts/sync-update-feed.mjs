/**
 * Generate data/update.json from the built artifacts.
 *
 *   node scripts/sync-update-feed.mjs [--version 0.2.4] [--check]
 *
 * REX's updater reads this file, compares versions itself, and downloads from
 * whatever URL each asset names. There is no server in that path: the site
 * publishes the manifest, a CDN serves it, and the comparison happens on the
 * machine being updated.
 *
 * The checksums are computed from the files in dist-installer/ — the bytes that
 * were actually built here — not from whatever the release host happens to be
 * serving. That is the point of generating it: an updater that downloads a
 * binary and cannot verify it is worse than one that offers no update at all,
 * and a hash typed by hand drifts the moment a build is repeated.
 *
 * `--check` exits non-zero if the file on disk disagrees with the artifacts,
 * which is what you want before publishing a release.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist-installer");
const OUT = path.join(ROOT, "data", "update.json");

const argv = process.argv.slice(2);
const arg = (n, d = null) => {
  const i = argv.indexOf("--" + n);
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : d;
};
const check = argv.includes("--check");

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const version = arg("version", pkg.version);
const repo = arg("repo", "https://github.com/rxdsec634/REX");
const base = `${repo.replace(/\/$/, "")}/releases/download/v${version}/`;

/**
 * Which artifact serves which platform.
 *
 * Linux gets the .deb rather than the tarball on purpose: both are "linux", and
 * an updater that offered two would have to guess. The .deb is the one that can
 * actually be applied by a package manager.
 *
 * GitHub replaces spaces in asset names with dots on upload, so the published
 * name is not the file name — hence both columns.
 */
const TARGETS = [
  { file: `REX Setup ${version}.exe`, asset: `REX.Setup.${version}.exe`, platform: "win32", arch: "x64" },
  { file: `rex_${version}_amd64.deb`, asset: `rex_${version}_amd64.deb`, platform: "linux", arch: "x64" },
];

const assets = [];
const missing = [];

for (const t of TARGETS) {
  const full = path.join(DIST, t.file);
  if (!fs.existsSync(full)) {
    missing.push(t.file);
    continue;
  }
  const buf = fs.readFileSync(full);
  assets.push({
    platform: t.platform,
    arch: t.arch,
    url: base + t.asset,
    size: buf.length,
    sha256: crypto.createHash("sha256").update(buf).digest("hex"),
  });
}

if (!assets.length) {
  console.error(`No artifacts found in ${DIST} for version ${version}. Build first.`);
  process.exit(1);
}

const existing = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, "utf8")) : null;
const previousNotes = existing?.channels?.stable?.find((r) => r.version === version)?.notes;

const feed = {
  $comment:
    "Generated by scripts/sync-update-feed.mjs from the built artifacts. The checksums are of the bytes built here, not of whatever the host serves. Never hand-edit: re-run the script.",
  channels: {
    stable: [
      {
        version,
        releasedAt: new Date().toISOString().slice(0, 10),
        mandatory: false,
        draft: false,
        notes: previousNotes || "",
        assets,
      },
    ],
  },
};

const next = JSON.stringify(feed, null, 2) + "\n";

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  // releasedAt moves every day the script runs; comparing it would make --check
  // fail for a reason nobody cares about.
  const strip = (s) => s.replace(/"releasedAt":\s*"[^"]*"/g, '"releasedAt":""');
  if (strip(current) !== strip(next)) {
    console.error("data/update.json is out of date. Run: node scripts/sync-update-feed.mjs");
    process.exit(1);
  }
  console.log("data/update.json is in sync.");
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, next);

console.log(`Wrote data/update.json for ${version} (${assets.length} assets).`);
for (const a of assets) {
  console.log(`  ${a.platform}/${a.arch}  ${(a.size / 1048576).toFixed(0)} MB  ${a.sha256.slice(0, 16)}…`);
}
if (missing.length) {
  console.warn(`  not built, so not offered: ${missing.join(", ")}`);
}
